#program for Demonstrating the Functionality of Arithmetic Operationa
#Arithematic Operations
a=float(input("Enter value of a: "))
b=float(input("Enter value of b: "))
print("\t Results of Arithmetic Operations")
print("\t\t Sum({},{})={}".format (a,b,a+b))
print("\t\t Sub({},{})={}".format (a,b,a-b))
print("\t\t Mul({},{})={}".format (a,b,a*b))
print("\t\t Div({},{})={}".format (a,b,a/b))
print("\t\t Mod Div({},{})={}".format (a,b,a//b))
print("\t\t Floor Div({},{})={}".format (a,b,a%b))
print("\t\t pow({},{})={}".format (a,b,a**b))